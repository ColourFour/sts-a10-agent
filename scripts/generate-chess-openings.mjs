import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Chess } from "chess.js";

const sourceCommit = "51a55d956b7ed0b9cd7853893744b1ca39cd2a05";
const sourceUrl = "https://github.com/lichess-org/chess-openings";
const dataDir = "data/chess-openings";
const outputPath = "src/applets/classic-games/chess-analysis/chessOpenings.generated.ts";
const volumes = ["a", "b", "c", "d", "e"];

function parseTsv(text) {
  const lines = text.trim().split(/\r?\n/);
  const headers = lines.shift()?.split("\t") ?? [];
  const ecoIndex = headers.indexOf("eco");
  const nameIndex = headers.indexOf("name");
  const pgnIndex = headers.indexOf("pgn");
  if (ecoIndex === -1 || nameIndex === -1 || pgnIndex === -1) {
    throw new Error(`Unexpected chess opening TSV header: ${headers.join(", ")}`);
  }

  return lines.map((line) => {
    const columns = line.split("\t");
    return {
      eco: columns[ecoIndex],
      name: columns[nameIndex],
      pgn: columns.slice(pgnIndex).join("\t"),
    };
  });
}

function deriveOpening(entry) {
  const chess = new Chess();
  chess.loadPgn(entry.pgn);
  const uci = chess.history({ verbose: true }).map((move) => `${move.from}${move.to}${move.promotion ?? ""}`);
  const fen = chess.fen();
  const epd = fen.split(" ").slice(0, 4).join(" ");
  const family = entry.name.split(":")[0].split(",")[0].trim();

  return {
    eco: entry.eco,
    epd,
    family,
    fen,
    name: entry.name,
    pgn: entry.pgn,
    ply: uci.length,
    uci,
    volume: entry.eco[0],
  };
}

const entries = [];
const failures = [];

for (const volume of volumes) {
  const sourcePath = join(dataDir, `${volume}.tsv`);
  for (const entry of parseTsv(readFileSync(sourcePath, "utf8"))) {
    try {
      entries.push(deriveOpening(entry));
    } catch (error) {
      failures.push(`${entry.eco} ${entry.name}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
}

if (failures.length > 0) {
  throw new Error(`Could not parse ${failures.length} opening(s):\n${failures.slice(0, 20).join("\n")}`);
}

entries.sort((left, right) => left.eco.localeCompare(right.eco) || left.name.localeCompare(right.name) || left.pgn.localeCompare(right.pgn));

const moduleBody = `// Generated by scripts/generate-chess-openings.mjs. Do not edit by hand.
// Source: ${sourceUrl}
// Source commit: ${sourceCommit}
// License: CC0-1.0; see data/chess-openings/COPYING.txt.
import type { OpeningBookEntry } from "./chessOpenings";

export const openingBookSource = {
  commit: ${JSON.stringify(sourceCommit)},
  entryCount: ${entries.length},
  license: "CC0-1.0",
  name: "lichess-org/chess-openings",
  url: ${JSON.stringify(sourceUrl)},
} as const;

export const openingBookEntries = JSON.parse(${JSON.stringify(JSON.stringify(entries))}) as OpeningBookEntry[];
`;

writeFileSync(outputPath, moduleBody);
console.log(`Generated ${entries.length} opening entries at ${outputPath}.`);
